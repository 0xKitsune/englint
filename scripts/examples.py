#!/usr/bin/env python3
"""Regenerate checked-in CLI reports; fail if an example has the wrong outcome."""
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parent.parent
subprocess.run(["cargo", "build", "--locked", "--quiet"], cwd=ROOT, check=True)
rows = []
for directory, config in [("prose", "englint.toml"), ("technical-spec", "profiles/technical-spec.toml"), ("tip", "profiles/tip.toml")]:
    for variant, status in [("before", 1), ("after", 0)]:
        source = f"examples/{directory}/{variant}.md"
        result = subprocess.run([str(ROOT / "target/debug/englint"), "--config", config, "--input-format", "markdown", "--format", "json", "--fail-on", "advice", source], cwd=ROOT, capture_output=True, text=True)
        if result.returncode != status:
            raise SystemExit(f"{source}: expected exit {status}, got {result.returncode}\n{result.stderr}{result.stdout}")
        (ROOT / f"examples/{directory}/{variant}.json").write_text(result.stdout)
        m = json.loads(result.stdout)[0]["metrics"]
        rows.append(f"| {directory}/{variant} | {m['words']} | {m['findings']} | {m['findings_per_100_words']:.2f} |")
(ROOT / "examples/results.md").write_text("# Example results\n\nGenerated by `python3 scripts/examples.py`. Counts describe these fixtures under their respective policies. A clean result does not prove factual or protocol correctness.\n\n| Example | Checked words | Findings | Findings per 100 words |\n| --- | ---: | ---: | ---: |\n" + "\n".join(rows) + "\n")
